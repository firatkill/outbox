import { parseOutboxConfig } from '../config.js';
import { OutboxError } from '../errors.js';
import { quoteIdent } from '../identifiers.js';
import { render } from '../sql/render.js';
import { BOOTSTRAP } from './bootstrap.js';
import { MIGRATIONS, migrationChecksum, REQUIRED_SCHEMA_VERSION } from './index.js';

/** Generate a migration script for an external migration tool.
 * @param options - Schema/prefix defaults are public/outbox_; the version range is exclusive/inclusive.
 * @example
 * const sql = migrationSql({ schema: 'app_events', fromVersion: 0 });
 */
export function migrationSql(
  options: { schema?: string; tablePrefix?: string; fromVersion?: number; toVersion?: number } = {},
): string {
  const config = parseOutboxConfig({ db: {}, schema: options.schema, tablePrefix: options.tablePrefix });
  const from = options.fromVersion ?? 0;
  const to = options.toVersion ?? REQUIRED_SCHEMA_VERSION;
  if (!Number.isSafeInteger(from) || from < 0 || !Number.isSafeInteger(to) || to < 0) {
    throw new OutboxError('OUTBOX_CONFIG', 'Migration versions must be non-negative safe integers');
  }
  let sql =
    `-- @firatkill/outbox schema migrations ${String(from + 1)}..${String(to)} for schema ${quoteIdent(config.schema)}, prefix ${quoteIdent(config.tablePrefix)}\n` +
    `-- Generated by @firatkill/outbox ${__OUTBOX_VERSION__}. Run inside one transaction. Do not edit.\n` +
    render(BOOTSTRAP, config);
  for (const migration of MIGRATIONS.filter((entry) => entry.version > from && entry.version <= to)) {
    // Metadata and checksum are library constants, never caller-provided SQL values.
    sql +=
      `\n-- migration ${String(migration.version)}: ${migration.name}\n` +
      render(migration.template, config) +
      'insert into ' +
      config.names.migrations +
      ' (version, name, checksum)\n' +
      `  values (${String(migration.version)}, '${migration.name}', '${migrationChecksum(migration.template)}') on conflict (version) do nothing;\n`;
  }
  return sql;
}
