import { readFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { describe, expect, it } from 'vitest';
import { CLI_HELP, CLI_OPTIONS, redactPassword, resolveCliArgs } from '../../src/core/cli-args.js';
import { migrationSql } from '../../src/core/migrations/sql.js';

function parse(args: string[], url?: string) {
  const parsed = parseArgs({ args, options: CLI_OPTIONS, allowPositionals: true, strict: true });
  return resolveCliArgs(parsed.values, parsed.positionals, url);
}

describe('CLI options', () => {
  it('UT-12 TC-037 resolves every documented option and defaults', () => {
    expect(parse(['migrate'], 'postgres://fixture/db')).toEqual({
      command: 'migrate',
      url: 'postgres://fixture/db',
      schema: 'public',
      tablePrefix: 'outbox_',
      driver: undefined,
      dryRun: false,
      status: false,
      check: false,
      print: false,
      fromVersion: 0,
      json: false,
    });
    expect(
      parse([
        'migrate',
        '--url',
        'postgres://fixture/explicit',
        '--schema',
        'app_events',
        '--prefix',
        'ob_',
        '--driver',
        'pg',
        '--status',
        '--check',
        '--dry-run',
      ]),
    ).toMatchObject({
      url: 'postgres://fixture/explicit',
      schema: 'app_events',
      tablePrefix: 'ob_',
      driver: 'pg',
      status: true,
      check: true,
      dryRun: true,
    });
    expect(parse(['migrate', '--driver', 'postgres-js', '--print', '--from', '1'])).toMatchObject({
      driver: 'postgres-js',
      print: true,
      fromVersion: 1,
    });
    expect(parse(['stats', '--json'], 'postgres://fixture/db')).toMatchObject({ command: 'stats', json: true });
    for (const flag of ['-h', '--help']) expect(parse([flag]).command).toBe('help');
    for (const flag of ['-v', '--version']) expect(parse([flag]).command).toBe('version');
    expect(parse([]).command).toBe('help');
  });
  it('UT-12 TC-037 rejects unknown commands and options', () => {
    expect(() => parse(['unknown'])).toThrow('Unknown command');
    expect(() => parse(['migrate', '--unknown'])).toThrow('Unknown option');
    expect(() => parse(['migrate'])).toThrow('Missing URL');
  });
  it('UT-12 TC-037 snapshots the normative help text', () => {
    expect(CLI_HELP).toBe(readFileSync(new URL('../fixtures/cli-help.txt', import.meta.url), 'utf8'));
  });
  it('UT-12 TC-038 redacts URL passwords in errors', () => {
    expect(redactPassword('postgres://u:secret@h/db')).toBe('postgres://u:***@h/db');
    expect(
      redactPassword(
        'failure: postgres://u:fixture-secret@h/db; password fixture-secret',
        'postgres://u:fixture-secret@h/db',
      ),
    ).toBe('failure: postgres://u:***@h/db; password ***');
    expect(redactPassword('fixture secret', 'postgres://u:fixture%20secret@h/db')).toBe('***');
  });
  it('UT-12 TC-039 prints the requested migration range', () => {
    const all = migrationSql();
    expect(all.split('\n').slice(0, 3)).toEqual([
      '-- @firatkill/outbox schema migrations 1..1 for schema "public", prefix "outbox_"',
      `-- Generated by @firatkill/outbox ${__OUTBOX_VERSION__}. Run inside one transaction. Do not edit.`,
      'create schema if not exists "public";',
    ]);
    expect(all).toContain('-- migration 1: initial');
    expect(all).toMatch(/values \(1, 'initial', '[a-f0-9]{64}'\) on conflict \(version\) do nothing;/);
    const delta = migrationSql({ fromVersion: 1 });
    expect(delta).toContain('schema migrations 2..1');
    expect(delta).not.toContain('-- migration 1: initial');
    expect(delta).toContain('create table if not exists "public"."outbox_schema_migrations"');
  });
});
